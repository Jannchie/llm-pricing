// Regenerate the offline snapshot from models.dev.
//
// Run `pnpm sync`, review the diff, commit. Nothing in this package's price
// data is meant to be typed by hand — the only hand-maintained pricing
// facts left are the ones no upstream publishes at all (peak/off-peak
// schedules and fast-tier multipliers).
//
// The merge is APPEND-ONLY: a model that disappears upstream keeps its last
// known price. Stored model strings are immortal, and a row that silently
// prices at $0 is worse than a stale rate.

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://models.dev/api.json'
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'catalog', 'snapshot.json')

// Keep in sync with DEFAULT_PROVIDER_PRIORITY in src/catalog/modelsdev.ts.
// Only first-party providers are snapshotted: resellers and routers re-quote
// the same model at their own margin, and a bare model name must resolve to
// the price a user calling the vendor directly would actually pay.
const PROVIDERS = [
  'anthropic',
  'openai',
  'google',
  'deepseek',
  'xai',
  'meta',
  'mistral',
  'cohere',
  'alibaba',
  'zai',
  'moonshotai',
  'llama',
  'google-vertex',
  'amazon-bedrock',
  'azure',
]

const response = await fetch(SOURCE, { headers: { accept: 'application/json' } })
if (!response.ok) {
  console.error(`[sync] ${SOURCE} -> HTTP ${response.status}`)
  process.exit(1)
}
const api = await response.json()

const previous = JSON.parse(readFileSync(OUT, 'utf8'))
const models = { ...previous.models }

let added = 0
let changed = 0
const seen = new Set()
for (const provider of PROVIDERS) {
  for (const [id, model] of Object.entries(api[provider]?.models ?? {})) {
    const cost = model?.cost
    if (!cost || typeof cost.input !== 'number' || typeof cost.output !== 'number') {
      continue
    }
    // Placeholder rows advertise availability at 0/0; pricing a real
    // workload against those silently reports $0 spend.
    if (!(cost.input > 0 || cost.output > 0)) {
      continue
    }
    const key = id.toLowerCase()
    // First provider in PROVIDERS order wins a given bare model name.
    if (seen.has(key)) {
      continue
    }
    seen.add(key)
    const cacheRead = typeof cost.cache_read === 'number' ? cost.cache_read : cost.input * 0.1
    const cacheWrite = typeof cost.cache_write === 'number' ? cost.cache_write : cacheRead
    const row = [model.name ?? id, cost.input, cacheWrite, cacheRead, cost.output]
    const before = models[key]
    if (!before) {
      added++
    }
    else if (JSON.stringify(before) !== JSON.stringify(row)) {
      changed++
    }
    models[key] = row
  }
}

const removed = Object.keys(models).filter(k => !seen.has(k))
const keys = Object.keys(models).sort()

// Hand-rolled so each model stays on one line: this file is reviewed as a
// diff, and a repriced model should read as a one-line change rather than
// five.
const header = {
  $comment: 'GENERATED by scripts/sync-snapshot.mjs — do not edit by hand. Rows are [displayName, input, cacheWrite, cacheRead, output] in USD per million tokens. Append-only: entries upstream has dropped are retained.',
  source: SOURCE,
  syncedAt: new Date().toISOString().slice(0, 10),
}
const body = keys.map(k => `    ${JSON.stringify(k)}: ${JSON.stringify(models[k])}`).join(',\n')
writeFileSync(OUT, `{\n${
  Object.entries(header).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')
},\n  "models": {\n${body}\n  }\n}\n`)

console.log(`[sync] ${keys.length} models — ${added} added, ${changed} repriced, ${removed.length} retained after upstream removal`)
