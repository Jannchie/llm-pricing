// Regenerate the offline price archive from models.dev.
//
// Run `pnpm sync`, review the diff, commit. Nothing in this package's price
// data is meant to be typed by hand — the only hand-maintained pricing
// facts left are the ones no upstream publishes at all (peak/off-peak
// schedules and fast-tier multipliers).
//
// This builds an ARCHIVE, not a table. models.dev — like OpenRouter,
// LiteLLM and ccusage — publishes one number per model: whatever it costs
// today. Applied naively that re-prices history, so a vendor raising a rate
// silently inflates last month's bill. Each sync therefore *appends* a
// period dated today rather than overwriting, and the resulting schedule
// keeps old months on old rates.
//
// Two consequences worth knowing:
//
//   - An effective date is only as precise as the sync cadence. A price
//     that changed three weeks before a sync is dated at the sync. Sync
//     often if that matters.
//   - The merge is APPEND-ONLY in both directions: a model that disappears
//     upstream keeps its whole history. Stored model strings are immortal,
//     and a row that silently prices at $0 is worse than a stale rate.

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const SOURCE = 'https://models.dev/api.json'
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'catalog', 'snapshot.json')

// Keep in sync with DEFAULT_PROVIDER_PRIORITY in src/catalog/modelsdev.ts.
// Only first-party providers are archived: resellers and routers re-quote
// the same model at their own margin, and a bare model name must resolve to
// the price a user calling the vendor directly would actually pay.
const PROVIDERS = [
  'anthropic',
  'openai',
  'google',
  'deepseek',
  'xai',
  'meta',
  'mistral',
  'cohere',
  'alibaba',
  'zai',
  'moonshotai',
  'llama',
  'google-vertex',
  'amazon-bedrock',
  'azure',
]

const today = new Date().toISOString().slice(0, 10)

const response = await fetch(SOURCE, { headers: { accept: 'application/json' } })
if (!response.ok) {
  console.error(`[sync] ${SOURCE} -> HTTP ${response.status}`)
  process.exit(1)
}
const api = await response.json()

const previous = JSON.parse(readFileSync(OUT, 'utf8'))
/** id -> [displayName, periods] where a period is [fromDate|null, input, cacheWrite, cacheRead, output] */
const models = { ...previous.models }

let added = 0
let repriced = 0
const seen = new Set()
for (const provider of PROVIDERS) {
  for (const [id, model] of Object.entries(api[provider]?.models ?? {})) {
    const cost = model?.cost
    if (!cost || typeof cost.input !== 'number' || typeof cost.output !== 'number') {
      continue
    }
    // Placeholder rows advertise availability at 0/0; pricing a real
    // workload against those silently reports $0 spend.
    if (!(cost.input > 0 || cost.output > 0)) {
      continue
    }
    const key = id.toLowerCase()
    // First provider in PROVIDERS order wins a given bare model name.
    if (seen.has(key)) {
      continue
    }
    seen.add(key)
    const cacheRead = typeof cost.cache_read === 'number' ? cost.cache_read : cost.input * 0.1
    const cacheWrite = typeof cost.cache_write === 'number' ? cost.cache_write : cacheRead
    const rates = [cost.input, cacheWrite, cacheRead, cost.output]
    const displayName = model.name ?? id

    const before = models[key]
    if (!before) {
      // First observation. It opens at null (-Infinity) rather than today:
      // the model was priced this way before we started watching, and
      // dating it today would leave every earlier row unpriced.
      models[key] = [displayName, [[null, ...rates]]]
      added++
      continue
    }
    const periods = before[1]
    const latest = periods.at(-1)
    if (JSON.stringify(latest.slice(1)) === JSON.stringify(rates)) {
      // Unchanged. Refresh the display name only.
      models[key] = [displayName, periods]
      continue
    }
    // A reprice. If the latest period was recorded in this same sync (a
    // re-run on the same day), correct it in place instead of stacking two
    // periods on one date.
    const next = latest[0] === today
      ? [...periods.slice(0, -1), [today, ...rates]]
      : [...periods, [today, ...rates]]
    models[key] = [displayName, next]
    repriced++
  }
}

const retained = Object.keys(models).filter(k => !seen.has(k))
const keys = Object.keys(models).sort()

// Hand-rolled so each model stays on one line: this file is reviewed as a
// diff, and a reprice should read as a one-line change.
const header = {
  $comment: 'GENERATED by scripts/sync-snapshot.mjs — do not edit by hand. Each entry is [displayName, periods]; each period is [effectiveFrom|null, input, cacheWrite, cacheRead, output] in USD per million tokens. Append-only: periods accumulate so history is never re-priced, and entries upstream has dropped are retained.',
  source: SOURCE,
  syncedAt: today,
}
const body = keys.map(k => `    ${JSON.stringify(k)}: ${JSON.stringify(models[k])}`).join(',\n')
writeFileSync(OUT, `{\n${
  Object.entries(header).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')
},\n  "models": {\n${body}\n  }\n}\n`)

const scheduled = keys.filter(k => models[k][1].length > 1).length
console.log(`[sync] ${keys.length} models — ${added} added, ${repriced} repriced, ${scheduled} now carry a price history, ${retained.length} retained after upstream removal`)
